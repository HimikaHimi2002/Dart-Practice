void main() {
  //Integer
  int age = 24;
  int BirthYear = 2002;

  //Double
  double cgpa = 3.50;

  print(age);
  print(BirthYear);
  print(cgpa);

  //Arithmetic Operator
  print(10+10);
  print(10-5);
  print(10*8);
  print(10/5);

  //Integer Division
  print(10 ~/ 3);

  //Modulo/Remainder
print(10%3);
}